"""Generates init/SRPEntities.java from the original registration table (named_all/init/SRPEntities.java) and
porting/spec/entity_meta.json (sizes, fire immunity collected by srp_translate.py).

usage: python gen_entities.py <named_root> <project_root>
"""
import json
import os
import re
import sys

named, proj = sys.argv[1], sys.argv[2]
src = open(os.path.join(named, 'com/dhanantry/scapeandrunparasites/init/SRPEntities.java'), encoding='utf8', errors='replace').read()
meta = json.load(open(os.path.join(proj, 'porting/spec/entity_meta.json'), encoding='utf8'))

entries = []
# mobs
for m in re.finditer(r'SRPEntities\.CreateEntityMob\("(\w+)",\s*(\w+)\.class,\s*([^,]+),\s*([^,]+),\s*(\d+),\s*([^)]+)\)', src):
    entries.append(dict(kind='mob', name=m.group(1), cls=m.group(2), c1=m.group(3).strip(), c2=m.group(4).strip(), oid=int(m.group(5)), enabled=m.group(6).strip()))
for m in re.finditer(r'SRPEntities\.CreateEntityProjectile\("(\w+)",\s*(\w+)\.class,\s*(\d+)(?:,\s*(\d+))?\)', src):
    if m.group(4):
        entries.append(dict(kind='proj', name=m.group(1), cls=m.group(2), track=int(m.group(3)), interval=1, oid=int(m.group(4))))
    else:
        entries.append(dict(kind='proj', name=m.group(1), cls=m.group(2), track=64, interval=3, oid=int(m.group(3))))

# keep the original order (order of appearance in the source)
order = {}
for i, m in enumerate(re.finditer(r'SRPEntities\.CreateEntity\w+\("(\w+)"', src)):
    order[m.group(1)] = i
entries.sort(key=lambda e: order[e['name']])

# which classes are living (extend Monster chain)? decided by presence of createAttributes in the translated output later;
# here: kind == mob -> living.
lines = []
imports = set()
for e in entries:
    cls = e['cls']
    pk = None
    for dp, _, fs in os.walk(os.path.join(named, 'com/dhanantry/scapeandrunparasites/entity')):
        if cls + '.java' in fs:
            pk = os.path.relpath(dp, os.path.join(named, 'com/dhanantry/scapeandrunparasites')).replace(os.sep, '.')
            break
    if pk is None:
        raise SystemExit('class not found: ' + cls)
    imports.add('com.dhanantry.scapeandrunparasites.' + pk + '.' + cls)
    e['pkg'] = pk
    sz = meta.get(cls, {}).get('size', ['0.6f', '1.8f'])
    e['w'], e['h'] = sz
    e['fire'] = meta.get(cls, {}).get('fireImmune', False)


def fnum(s):
    s = s.strip()
    return s if s.endswith('f') or not re.fullmatch(r'-?[\d.]+', s) else s + 'f'


out = []
out.append('package com.dhanantry.scapeandrunparasites.init;\n')
out.append('import com.dhanantry.scapeandrunparasites.ScapeAndRunParasites;')
out.append('import com.dhanantry.scapeandrunparasites.config.SRPConfigMobs;')
for i in sorted(imports):
    out.append('import %s;' % i)
out.append('''import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.BooleanSupplier;
import net.minecraft.core.registries.Registries;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.MobCategory;
import net.neoforged.neoforge.event.entity.EntityAttributeCreationEvent;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredRegister;

/**
 * Entity registry, generated by porting/tools/gen_entities.py from the 1.12.2 registration table
 * (same registry names). Sizes come from the original constructors. {@link #ENABLED} holds the
 * original per-mob config switch (1.12 skipped registration of disabled mobs, see PORTING_NOTES.md).
 */
public final class SRPEntities {
    public static final DeferredRegister<EntityType<?>> ENTITIES = DeferredRegister.create(Registries.ENTITY_TYPE, ScapeAndRunParasites.MODID);

    /** registry name -> original "active" switch */
    public static final Map<String, BooleanSupplier> ENABLED = new LinkedHashMap<>();
    /** registry name -> {primary, secondary} egg colours of the mobs that get a spawn egg */
    public static final Map<String, int[]> EGG_COLORS = new LinkedHashMap<>();
    /** attribute registration callbacks */
    private static final List<Runnable> NOOP = new ArrayList<>();

    private SRPEntities() {}

    private static <T extends Entity> DeferredHolder<EntityType<?>, EntityType<T>> mob(String name, EntityType.EntityFactory<T> factory, float w, float h,
            boolean fireImmune, int c1, int c2, BooleanSupplier enabled) {
        ENABLED.put(name, enabled);
        EGG_COLORS.put(name, new int[]{c1, c2});
        return ENTITIES.register(name, () -> {
            EntityType.Builder<T> b = EntityType.Builder.of(factory, MobCategory.MONSTER).sized(w, h).clientTrackingRange(4).updateInterval(3);
            if (fireImmune) {
                b.fireImmune();
            }
            return b.build(ScapeAndRunParasites.MODID + ":" + name);
        });
    }

    private static <T extends Entity> DeferredHolder<EntityType<?>, EntityType<T>> proj(String name, EntityType.EntityFactory<T> factory, float w, float h,
            boolean fireImmune, int track, int interval) {
        return ENTITIES.register(name, () -> {
            EntityType.Builder<T> b = EntityType.Builder.of(factory, MobCategory.MISC).sized(w, h).clientTrackingRange(Math.max(4, track / 16)).updateInterval(interval);
            if (fireImmune) {
                b.fireImmune();
            }
            return b.build(ScapeAndRunParasites.MODID + ":" + name);
        });
    }
''')
for e in entries:
    const = e['name'].upper()
    cls = e['cls']
    if e['kind'] == 'mob':
        out.append('    public static final DeferredHolder<EntityType<?>, EntityType<%s>> %s = mob("%s", %s::new, %s, %s, %s, %s, %s, () -> %s);' % (
            cls, const, e['name'], cls, fnum(e['w']), fnum(e['h']), 'true' if e['fire'] else 'false', e['c1'], e['c2'], e['enabled']))
    else:
        out.append('    public static final DeferredHolder<EntityType<?>, EntityType<%s>> %s = proj("%s", %s::new, %s, %s, %s, %d, %d);' % (
            cls, const, e['name'], cls, fnum(e['w']), fnum(e['h']), 'true' if e['fire'] else 'false', e['track'], e['interval']))

out.append('\n    /** Registers the attribute suppliers of all living parasite entities. */')
out.append('    public static void registerAttributes(EntityAttributeCreationEvent event) {')
for e in entries:
    if e['kind'] == 'mob':
        out.append('        event.put(%s.get(), %s.createAttributes().build());' % (e['name'].upper(), e['cls']))
out.append('    }')
out.append('}')
dest = os.path.join(proj, 'src/main/java/com/dhanantry/scapeandrunparasites/init/SRPEntities.java')
open(dest, 'w', encoding='utf8').write('\n'.join(out) + '\n')
print('entries', len(entries), 'mobs', sum(1 for e in entries if e['kind'] == 'mob'))
