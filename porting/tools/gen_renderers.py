"""Generates client/ClientRenderers.java (entity renderer registration) from the 1.12 SRPRenderHandler.

Only renderers that exist in src/main/java are registered; the others are listed in a comment block of the generated file.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(ROOT, 'src/main/java/com/dhanantry/scapeandrunparasites')
handler = open('C:/srp_work/named_all/com/dhanantry/scapeandrunparasites/util/handlers/SRPRenderHandler.java', encoding='utf8').read()
entities = open(os.path.join(SRC, 'init/SRPEntities.java'), encoding='utf8').read()
holder = {}
for cls, name in re.findall(r'EntityType<(\w+)>> (\w+) =', entities):
    holder[cls] = name

render_files = {}
for dp, _, fs in os.walk(os.path.join(SRC, 'client/renderer')):
    for f in fs:
        if f.endswith('.java'):
            render_files[f[:-5]] = os.path.relpath(os.path.join(dp, f), SRC)[:-5].replace(os.sep, '.')

pairs = []
for chunk in handler.split('registerEntityRenderingHandler(')[1:]:
    m = re.match(r'(\w+)\.class', chunk)
    r = re.search(r'return new (\w+)\(manager([^)]*)\);', chunk.split('registerEntityRenderingHandler(')[0])
    if m and r:
        pairs.append((m.group(1), r.group(1), r.group(2)))
lines = []
missing = []
seen = set()
for ent, rend, extra in pairs:
    if ent in seen:
        continue
    seen.add(ent)
    if ent not in holder:
        missing.append('%s (entity type not registered) -> %s' % (ent, rend))
        continue
    if rend not in render_files:
        missing.append('%s -> %s (renderer not ported yet)' % (ent, rend))
        continue
    lines.append('        e.registerEntityRenderer(SRPEntities.%s.get(), ctx -> new %s(new RenderManager(ctx)%s));' % (holder[ent], rend, extra))
imports = sorted(set('import com.dhanantry.scapeandrunparasites.%s;' % render_files[r] for _, r, _ in pairs if r in render_files))

out = '''package com.dhanantry.scapeandrunparasites.client;

import com.dhanantry.scapeandrunparasites.ScapeAndRunParasites;
import com.dhanantry.scapeandrunparasites.client.legacy.RenderManager;
import com.dhanantry.scapeandrunparasites.init.SRPEntities;
%s
import net.neoforged.api.distmarker.Dist;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.client.event.EntityRenderersEvent;

/** Entity renderer registration, generated by porting/tools/gen_renderers.py from the 1.12 SRPRenderHandler. */
@EventBusSubscriber(modid = ScapeAndRunParasites.MODID, value = Dist.CLIENT)
public final class ClientRenderers {
    private ClientRenderers() {
    }

    @SubscribeEvent
    public static void onRegisterRenderers(EntityRenderersEvent.RegisterRenderers e) {
%s
    }
    /* not registered yet:
%s
     */
}
''' % ('\n'.join(imports), '\n'.join(lines), '\n'.join('     ' + m for m in missing))
open(os.path.join(SRC, 'client/ClientRenderers.java'), 'w', encoding='utf8').write(out)
print(len(lines), 'registered;', len(missing), 'missing')
for m in missing:
    print(m)
