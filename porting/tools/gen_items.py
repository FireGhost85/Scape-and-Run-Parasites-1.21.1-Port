"""Generates init/SRPItems.java from the registration code of the 1.12.2 SRPItems.init().

usage: python gen_items.py <named_root> <project_root>
Every `field = new Class(args);` becomes `DeferredItem<Class> field = ITEMS.register(name, () -> new Class(args))`.
The constructor arguments are passed through unchanged (the item classes keep the 1.12 "name" parameter).
"""
import os
import re
import sys

named, proj = sys.argv[1], sys.argv[2]
root = os.path.join(named, 'com/dhanantry/scapeandrunparasites/')
src = open(root + 'init/SRPItems.java', encoding='utf8', errors='replace').read()
src = re.sub(r'func_\d+_\w+/\*([^*]*)\*/', r'\1', src)
init = src[src.index('public static void init'):]
init = init[:init.index('static {')]

NO_ARG_NAMES = {
    'FOG_BOTTLE': 'fog_bottle', 'SRP_FIELD_GUIDE': 'srp_field_guide', 'THORNSHADE_DECANTER': 'thornshade_decanter', 'pearl': 'pearl',
    'itemThornshadeBerry': 'thornshade_berry', 'bookofvengeance': 'book_of_vengeance',
}
SLOT = {'HEAD': 'ArmorItem.Type.HELMET', 'CHEST': 'ArmorItem.Type.CHESTPLATE', 'LEGS': 'ArmorItem.Type.LEGGINGS', 'FEET': 'ArmorItem.Type.BOOTS'}

rows = []
for m in re.finditer(r'^\s*(\w+) = (SRPItems\.makeModule\()?(?:new )?(\w+)\(?(.*?)\)?;\s*$', init, flags=re.M):
    pass
lines = init.split('\n')
for ln in lines:
    ln = ln.strip()
    m = re.match(r'(\w+) = SRPItems\.makeModule\("(\w+)", (ItemModule\.Kind\.\w+)\);', ln)
    if m:
        rows.append(dict(field=m.group(1), cls='ItemModule', name=m.group(2), args='"%s", %s' % (m.group(2), m.group(3)), typ='ItemModule'))
        continue
    m = re.match(r'(\w+) = new (\w+)\((.*)\);$', ln)
    if not m:
        continue
    field, cls, args = m.groups()
    if cls == 'ItemMobSpawner':
        name = 'itemmobspawner_' + args.strip().strip('"')
    elif field in NO_ARG_NAMES:
        name = NO_ARG_NAMES[field]
    else:
        parts = [p.strip() for p in args.split(',')]
        lit = [p for p in parts if p.startswith('"')]
        name = lit[0].strip('"')
        if cls.startswith('WeaponMelee') or cls == 'WeaponToolRangeBase':
            name = 'weapon_' + name
        elif cls == 'WeaponToolArmorBase':
            name = 'armor_' + name
    args2 = args.replace('MATERIAL_LIVING', 'SRPToolMaterials.LIVING').replace('ARMOR_LIVING', 'SRPArmorMaterials.LIVING') \
        .replace('ARMOR_SENTIENT', 'SRPArmorMaterials.SENTIENT').replace('ARMOR_MOBILITY', 'SRPArmorMaterials.MOBILITY')
    args2 = re.sub(r'EntityEquipmentSlot\.(\w+)', lambda mm: SLOT[mm.group(1)], args2)
    rows.append(dict(field=field, cls=cls, name=name, args=args2, typ=cls))

# extra items that the 1.12 static initialiser creates
rows.append(dict(field='VECTOR_MAP', cls='ItemVectorMapReport', name='vector_map', args='"vector_map"', typ='ItemVectorMapReport'))

out = []
out.append('package com.dhanantry.scapeandrunparasites.init;\n')
out.append('''import com.dhanantry.scapeandrunparasites.ScapeAndRunParasites;
import com.dhanantry.scapeandrunparasites.config.SRPConfig;
import net.minecraft.world.item.ArmorItem;
import net.minecraft.world.item.Item;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.registries.DeferredItem;
import net.neoforged.neoforge.registries.DeferredRegister;

/**
 * Item registry, generated by porting/tools/gen_items.py from the 1.12.2 SRPItems.init() (same registry names and
 * constructor arguments, original order). Block items are registered with the blocks in {@link SRPBlocks}.
 */
public final class SRPItems {
    public static final DeferredRegister.Items ITEMS = DeferredRegister.createItems(ScapeAndRunParasites.MODID);

    private SRPItems() {}

    public static void register(IEventBus bus) {
        ITEMS.register(bus);
    }
''')
seen = set()
for r in rows:
    if r['name'] in seen:
        raise SystemExit('duplicate item name ' + r['name'])
    seen.add(r['name'])
    out.append('    public static final DeferredItem<%s> %s = ITEMS.register("%s", () -> new %s(%s));' % (r['typ'], r['field'], r['name'], r['cls'], r['args']))
out.append('}')
text = '\n'.join(out) + '\n'
dest = os.path.join(proj, 'src/main/java/com/dhanantry/scapeandrunparasites/init/SRPItems.java')
open(dest, 'w', encoding='utf8').write(text)
print('items', len(rows))
