package com.dhanantry.scapeandrunparasites.util;

import com.dhanantry.scapeandrunparasites.ScapeAndRunParasites;
import com.dhanantry.scapeandrunparasites.block.IStagedBlock;
import com.dhanantry.scapeandrunparasites.block.IVariantBlock;
import com.google.gson.Gson;
import com.google.gson.JsonObject;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import javax.annotation.Nullable;
import net.minecraft.commands.arguments.blocks.BlockStateParser;
import net.minecraft.core.Direction;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.RotatedPillarBlock;
import net.minecraft.world.level.block.SlabBlock;
import net.minecraft.world.level.block.StairBlock;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.properties.Half;
import net.minecraft.world.level.block.state.properties.Property;
import net.minecraft.world.level.block.state.properties.SlabType;

/**
 * Block strings of the config files. The 1.12 format {@code namespace:name:meta} (the defaults of the original) and the 1.21
 * format {@code namespace:name} or {@code namespace:name[property=value]} are both accepted.
 *
 * <p>A legacy string is resolved in this order: the vanilla {@code metas} table of {@code srparasites_meta_map.json} (generated by
 * {@code porting/tools/gen_meta_map.py}); the legacy {@code renames} table; the registry. The meta of an SRP block is read from
 * the block class: the variant ordinal (plus bit 8 for the top half of a slab), the infestation stage, the slab half, the stairs
 * orientation or the pillar axis. A meta that the 1.12 block did not have gives {@code null}.
 */
public final class BlockIds {
    private static final Map<String, String> RENAMES = new HashMap<>();
    private static final Map<String, Map<Integer, String>> METAS = new HashMap<>();
    private static final Map<String, BlockState> CACHE = new ConcurrentHashMap<>();

    static {
        try (InputStream in = BlockIds.class.getResourceAsStream("/srparasites_meta_map.json")) {
            if (in != null) {
                JsonObject root = new Gson().fromJson(new InputStreamReader(in, StandardCharsets.UTF_8), JsonObject.class);
                root.getAsJsonObject("renames").entrySet().forEach(e -> RENAMES.put(e.getKey(), e.getValue().getAsString()));
                root.getAsJsonObject("metas").entrySet().forEach(e -> {
                    Map<Integer, String> byMeta = new HashMap<>();
                    e.getValue().getAsJsonObject().entrySet().forEach(m -> byMeta.put(Integer.parseInt(m.getKey()), m.getValue().getAsString()));
                    METAS.put(e.getKey(), byMeta);
                });
            }
        } catch (Exception e) {
            ScapeAndRunParasites.LOGGER.error("[BlockIds] could not read srparasites_meta_map.json", e);
        }
    }

    private BlockIds() {
    }

    /** The state of the string, or {@code fallback} (with a warning) when it is empty, unknown or has an invalid meta. */
    public static BlockState parse(@Nullable String s, BlockState fallback) {
        BlockState state = tryParse(s);
        if (state == null) {
            ScapeAndRunParasites.LOGGER.warn("[BlockIds] unknown block '{}', using fallback {}", s, fallback);
            return fallback;
        }
        return state;
    }

    /**
     * The 1.21 replacement of the 1.12 "name;meta" strings the parasites collect for their cysts: the registry name, followed
     * by the non-default properties in vanilla notation ({@code srparasites:infestedbush[variant=a]}). {@link #tryParse} reads it back.
     */
    public static String stateString(BlockState state) {
        StringBuilder sb = new StringBuilder(BuiltInRegistries.BLOCK.getKey(state.getBlock()).toString());
        BlockState def = state.getBlock().defaultBlockState();
        StringBuilder props = new StringBuilder();
        for (Property<?> p : state.getProperties()) {
            if (state.getValue(p).equals(def.getValue(p))) {
                continue;
            }
            if (props.length() > 0) {
                props.append(',');
            }
            props.append(p.getName()).append('=').append(valueName(state, p));
        }
        if (props.length() > 0) {
            sb.append('[').append(props).append(']');
        }
        return sb.toString();
    }

    @SuppressWarnings({"unchecked", "rawtypes"})
    private static String valueName(BlockState state, Property p) {
        return p.getName(state.getValue(p));
    }

    /** The state of the string; air (with a warning) when it cannot be resolved. */
    public static BlockState parse(@Nullable String s) {
        return parse(s, Blocks.AIR.defaultBlockState());
    }

    /** The block of the string, ignoring the meta. */
    @Nullable
    public static Block parseBlock(@Nullable String s) {
        BlockState state = tryParse(s);
        return state == null ? null : state.getBlock();
    }

    /** True when the state is exactly the state the string stands for. */
    public static boolean matches(BlockState state, @Nullable String s) {
        BlockState other = tryParse(s);
        return other != null && other == state;
    }

    @Nullable
    public static BlockState tryParse(@Nullable String s) {
        if (s == null || s.isBlank()) {
            return null;
        }
        String key = s.trim();
        BlockState cached = CACHE.get(key);
        if (cached != null) {
            return cached;
        }
        BlockState state = resolve(key);
        if (state != null) {
            CACHE.put(key, state);
        }
        return state;
    }

    @Nullable
    private static BlockState resolve(String s) {
        if (s.indexOf('[') >= 0) {
            return parseState(s);
        }
        String[] parts = s.split(":");
        String ns;
        String name;
        int meta = 0;
        boolean hasMeta = false;
        try {
            if (parts.length == 3) {
                ns = parts[0];
                name = parts[1];
                meta = Integer.parseInt(parts[2].trim());
                hasMeta = true;
            } else if (parts.length == 2) {
                ns = parts[0];
                name = parts[1];
            } else if (parts.length == 1) {
                ns = "minecraft";
                name = parts[0];
            } else {
                return null;
            }
        } catch (NumberFormatException e) {
            return null;
        }
        String legacy = ns + ":" + name;
        Map<Integer, String> table = METAS.get(legacy);
        if (table != null) {
            String state = table.get(meta);
            return state == null ? null : parseState(state);
        }
        String id = RENAMES.getOrDefault(legacy, legacy);
        ResourceLocation rl = ResourceLocation.tryParse(id);
        if (rl == null) {
            return null;
        }
        Optional<Block> block = BuiltInRegistries.BLOCK.getOptional(rl);
        if (block.isEmpty()) {
            return null;
        }
        if (ScapeAndRunParasites.MODID.equals(rl.getNamespace())) {
            return hasMeta ? legacyState(block.get(), meta) : block.get().defaultBlockState();
        }
        return meta == 0 ? block.get().defaultBlockState() : null;
    }

    @Nullable
    private static BlockState parseState(String state) {
        try {
            return BlockStateParser.parseForBlock(BuiltInRegistries.BLOCK.asLookup(), state, false).blockState();
        } catch (Exception e) {
            return null;
        }
    }

    /** The 1.12 {@code getStateFromMeta} of an SRP block. */
    @Nullable
    @SuppressWarnings({"unchecked", "rawtypes"})
    public static BlockState legacyState(Block block, int meta) {
        BlockState state = block.defaultBlockState();
        if (block instanceof IVariantBlock<?> variant) {
            Enum<?>[] values = variant.getVariants();
            boolean slab = block instanceof SlabBlock;
            int index = slab ? meta & 7 : meta;
            if (index < 0 || index >= values.length) {
                return null;
            }
            state = state.setValue((Property) variant.getVariantProperty(), (Comparable) values[index]);
            if (slab && state.hasProperty(SlabBlock.TYPE)) {
                state = state.setValue(SlabBlock.TYPE, (meta & 8) != 0 ? SlabType.TOP : SlabType.BOTTOM);
            }
            return state;
        }
        if (block instanceof IStagedBlock staged && staged.getStageProperty() != null) {
            return state.setValue(staged.getStageProperty(), Math.max(0, Math.min(5, meta)));
        }
        if (block instanceof SlabBlock) {
            return state.setValue(SlabBlock.TYPE, (meta & 8) != 0 ? SlabType.TOP : SlabType.BOTTOM);
        }
        if (block instanceof StairBlock) {
            Direction facing = switch (meta & 3) {
                case 0 -> Direction.EAST;
                case 1 -> Direction.WEST;
                case 2 -> Direction.SOUTH;
                default -> Direction.NORTH;
            };
            return state.setValue(StairBlock.FACING, facing).setValue(StairBlock.HALF, (meta & 4) != 0 ? Half.TOP : Half.BOTTOM);
        }
        if (block instanceof RotatedPillarBlock) {
            Direction.Axis axis = switch (meta & 12) {
                case 4 -> Direction.Axis.X;
                case 8 -> Direction.Axis.Z;
                default -> Direction.Axis.Y;
            };
            return state.setValue(RotatedPillarBlock.AXIS, axis);
        }
        return meta == 0 ? state : null;
    }

    /** The 1.12 {@code getMetaFromState} of an SRP block: variant ordinal (plus 8 for a top slab), infestation stage or 0. */
    public static int legacyMeta(BlockState state) {
        Block block = state.getBlock();
        if (block instanceof IVariantBlock<?> variant) {
            Enum<?> value = (Enum<?>) state.getValue((Property) variant.getVariantProperty());
            int meta = value.ordinal();
            if (block instanceof SlabBlock && state.hasProperty(SlabBlock.TYPE) && state.getValue(SlabBlock.TYPE) == SlabType.TOP) {
                meta |= 8;
            }
            return meta;
        }
        if (block instanceof IStagedBlock staged && staged.getStageProperty() != null) {
            return state.getValue(staged.getStageProperty());
        }
        if (block instanceof SlabBlock && state.hasProperty(SlabBlock.TYPE) && state.getValue(SlabBlock.TYPE) == SlabType.TOP) {
            return 8;
        }
        return 0;
    }
}
